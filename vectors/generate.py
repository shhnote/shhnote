import base64
import hashlib
import hmac
import json
import struct
from pathlib import Path

from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.argon2 import Argon2id

VERSION = 1
CHUNK_SIZE = 65536
HEADER_LEN = 95
INFO_LOOKUP = b"shhnote/lookup/v1"
INFO_KEK_DIRECT = b"shhnote/kek-direct/v1"
INFO_KEK_PASS = b"shhnote/kek-pass/v1"
DEFAULT_ARGON = (65536, 3, 1)
# Reduced cost keeps the test suites fast; it is still inside the client bounds.
FAST_ARGON = (8192, 1, 1)
ARGON_BOUNDS = {"m": [8192, 262144], "t": [1, 8], "p": [1, 4]}

OUT = Path(__file__).with_name("v1.json")


# All "random" values are derived from labels so the file can be regenerated byte for byte.
def fixed(label: str, n: int) -> bytes:
    out = b""
    counter = 0
    while len(out) < n:
        out += hashlib.sha256(f"shhnote-vectors-v{VERSION}/{label}/{counter}".encode()).digest()
        counter += 1
    return out[:n]


def hkdf_sha256(ikm: bytes, info: bytes, length: int = 32) -> bytes:
    # Empty salt: RFC 5869 says that means HashLen zero bytes.
    prk = hmac.new(b"\x00" * 32, ikm, hashlib.sha256).digest()
    okm = b""
    block = b""
    counter = 1
    while len(okm) < length:
        block = hmac.new(prk, block + info + bytes([counter]), hashlib.sha256).digest()
        okm += block
        counter += 1
    return okm[:length]


def argon2id(passphrase: str, salt: bytes, m: int, t: int, p: int) -> bytes:
    kdf = Argon2id(salt=salt, length=32, iterations=t, lanes=p, memory_cost=m)
    return kdf.derive(passphrase.encode())


def padme(length: int) -> int:
    e = length.bit_length() - 1
    s = e.bit_length()
    z = e - s
    mask = (1 << z) - 1
    return (length + mask) & ~mask


def padded_size(length: int, policy: dict) -> int:
    if policy["mode"] == "padme":
        return padme(max(length, policy["min"]))
    for entry in policy["ladder"]:
        if entry >= length:
            return entry
    raise ValueError("payload larger than the biggest bucket")


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).decode().rstrip("=")


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode()


def build_payload(text, files):
    manifest = {"v": 1, "text": text, "files": [{"name": f["name"], "type": f["type"], "size": len(f["bytes"])} for f in files]}
    manifest_json = json.dumps(manifest, separators=(",", ":"), ensure_ascii=False)
    manifest_bytes = manifest_json.encode()
    payload = struct.pack(">I", len(manifest_bytes)) + manifest_bytes + b"".join(f["bytes"] for f in files)
    return manifest_json, payload


def encrypt_chunks(ek: bytes, nonce_prefix: bytes, padded: bytes, last_flag_on_final=True) -> list[bytes]:
    aead = AESGCM(ek)
    chunks = []
    for i in range(0, max(1, -(-len(padded) // CHUNK_SIZE))):
        start = i * CHUNK_SIZE
        chunk = padded[start : start + CHUNK_SIZE]
        last = start + CHUNK_SIZE >= len(padded)
        flag = 1 if (last and last_flag_on_final) else 0
        nonce = nonce_prefix + struct.pack(">I", i) + bytes([flag])
        chunks.append(aead.encrypt(nonce, chunk, None))
    return chunks


def make_vector(name, *, text, files, passphrase, argon, policy):
    seed = fixed(f"{name}/seed", 32)
    burn_token = fixed(f"{name}/burn", 32)
    ek = fixed(f"{name}/ek", 32)
    salt = fixed(f"{name}/salt", 16)
    wrap_iv = fixed(f"{name}/wrap-iv", 12)
    nonce_prefix = fixed(f"{name}/nonce-prefix", 7)
    m, t, p = argon

    lookup = hkdf_sha256(seed, INFO_LOOKUP)
    if passphrase is None:
        kek = hkdf_sha256(seed, INFO_KEK_DIRECT)
        pass_key = None
    else:
        pass_key = argon2id(passphrase, salt, m, t, p)
        kek = hkdf_sha256(seed + pass_key, INFO_KEK_PASS)
    wrapped_ek = AESGCM(kek).encrypt(wrap_iv, ek, None)

    manifest_json, payload = build_payload(text, files)
    bucket = padded_size(len(payload) + 4, policy)
    padded = struct.pack(">I", len(payload)) + payload
    padded += b"\x00" * (bucket - len(padded))
    chunks = encrypt_chunks(ek, nonce_prefix, padded)

    header = salt + struct.pack(">III", m, t, p) + wrap_iv + wrapped_ek + nonce_prefix
    assert len(header) == HEADER_LEN
    blob = header + b"".join(chunks)
    assert len(blob) == HEADER_LEN + bucket + 16 * len(chunks)

    return {
        "name": name,
        "inputs": {
            "seed": seed.hex(),
            "burn_token": burn_token.hex(),
            "passphrase": passphrase,
            "argon2": {"m": m, "t": t, "p": p},
            "text": text,
            "files": [{"name": f["name"], "type": f["type"], "bytes_base64": b64(f["bytes"])} for f in files],
            "ek": ek.hex(),
            "salt": salt.hex(),
            "wrap_iv": wrap_iv.hex(),
            "nonce_prefix": nonce_prefix.hex(),
            "padding": policy,
        },
        "expected": {
            "fragment": b64url(bytes([VERSION]) + seed),
            "burn_fragment": b64url(bytes([VERSION]) + burn_token),
            "lookup": lookup.hex(),
            "lookup_key": hashlib.sha256(lookup).hexdigest(),
            "burn_key": hashlib.sha256(burn_token).hexdigest(),
            "pass_key": pass_key.hex() if pass_key else None,
            "kek": kek.hex(),
            "wrapped_ek": wrapped_ek.hex(),
            "manifest": manifest_json,
            "payload_len": len(payload),
            "payload_sha256": hashlib.sha256(payload).hexdigest(),
            "bucket": bucket,
            "padded_sha256": hashlib.sha256(padded).hexdigest(),
            "chunk_count": len(chunks),
            "blob_len": len(blob),
            "header": header.hex(),
            "blob_base64": b64(blob),
        },
        "_blob": blob,
        "_ek": ek,
        "_nonce_prefix": nonce_prefix,
        "_padded": padded,
    }


def strip_private(vector: dict) -> dict:
    return {k: v for k, v in vector.items() if not k.startswith("_")}


def flip(data: bytes, offset: int) -> bytes:
    out = bytearray(data)
    out[offset] ^= 0x01
    return bytes(out)


def main():
    padme_4k = {"mode": "padme", "min": 4096}
    padme_64k = {"mode": "padme", "min": 65536}
    buckets = {"mode": "buckets", "ladder": [4096, 16384, 65536]}

    png_like = b"\x89PNG\r\n\x1a\n" + fixed("png-body", 1200)
    small_txt = "line one\nline two\n".encode()

    vectors = [
        make_vector("text-direct", text="hello, world", files=[], passphrase=None, argon=DEFAULT_ARGON, policy=padme_4k),
        make_vector("text-passphrase", text="hello, world", files=[], passphrase="correct horse battery staple", argon=FAST_ARGON, policy=padme_4k),
        make_vector(
            "text-and-files-direct",
            text="Two attachments. Second file name is UTF-8. 🔐",
            files=[{"name": "notes.txt", "type": "text/plain", "bytes": small_txt}, {"name": "résumé.png", "type": "image/png", "bytes": png_like}],
            passphrase=None,
            argon=DEFAULT_ARGON,
            policy=padme_4k,
        ),
        make_vector(
            "files-only-passphrase-defaults",
            text=None,
            files=[{"name": "recovery-key.asc", "type": "application/pgp-keys", "bytes": fixed("asc-body", 3100)}],
            passphrase="pässwörd — with unicode",
            argon=DEFAULT_ARGON,
            policy=padme_4k,
        ),
        make_vector("buckets-policy", text="x" * 5000, files=[], passphrase=None, argon=DEFAULT_ARGON, policy=buckets),
        make_vector("text-direct-64k-min", text="short", files=[], passphrase=None, argon=DEFAULT_ARGON, policy=padme_64k),
        make_vector(
            "multi-chunk",
            text=None,
            files=[{"name": "big.bin", "type": "application/octet-stream", "bytes": fixed("big-body", 70000)}],
            passphrase=None,
            argon=DEFAULT_ARGON,
            policy=padme_64k,
        ),
    ]

    # Boundary cases: payload_len + 4 lands exactly on a bucket, and one byte over it.
    _, probe = build_payload("", [])
    overhead = len(probe)
    exact = make_vector("boundary-exact", text="a" * (4096 - 4 - overhead), files=[], passphrase=None, argon=DEFAULT_ARGON, policy=padme_4k)
    assert exact["expected"]["bucket"] == 4096 and exact["expected"]["payload_len"] + 4 == 4096
    over = make_vector("boundary-plus-one", text="a" * (4096 - 4 - overhead + 1), files=[], passphrase=None, argon=DEFAULT_ARGON, policy=padme_4k)
    assert over["expected"]["bucket"] == 4352
    vectors += [exact, over]

    direct, passphrase = vectors[0], vectors[1]
    assert direct["expected"]["blob_len"] == passphrase["expected"]["blob_len"]

    rejects = []

    def reject(name, base, blob, reason):
        rejects.append({"name": name, "base": base["name"], "reason": reason, "blob_len": len(blob), "blob_base64": b64(blob)})

    blob = direct["_blob"]
    reject("tag-tampered", direct, flip(blob, len(blob) - 1), "last chunk tag fails to authenticate")
    reject("wrapped-ek-tampered", direct, flip(blob, 40), "wrapped_EK fails to unwrap in direct mode; the client would prompt for a passphrase that does not exist")
    reject("truncated", direct, blob[:-16], "length matches no valid padded size; the server refuses it and the client's final chunk fails to authenticate")

    pblob = passphrase["_blob"]
    reject("argon-m-below-bounds", passphrase, pblob[:16] + struct.pack(">I", 4096) + pblob[20:], "argon_m below the client bound; reject before running the KDF")
    reject("argon-m-above-bounds", passphrase, pblob[:16] + struct.pack(">I", 1 << 30) + pblob[20:], "argon_m above the client bound; reject before running the KDF")
    reject("argon-t-above-bounds", passphrase, pblob[:20] + struct.pack(">I", 9) + pblob[24:], "argon_t above the client bound; reject before running the KDF")

    no_last = encrypt_chunks(direct["_ek"], direct["_nonce_prefix"], direct["_padded"], last_flag_on_final=False)
    reject("last-flag-missing", direct, blob[:HEADER_LEN] + b"".join(no_last), "the final chunk was sealed without the last flag, so it fails to authenticate as the final chunk; this is how a truncated stream is detected")

    # Same content, but the length prefix claims the whole bucket, which is more than bucket - 4.
    bucket = direct["expected"]["bucket"]
    padded = struct.pack(">I", bucket) + direct["_padded"][4:]
    chunks = encrypt_chunks(direct["_ek"], direct["_nonce_prefix"], padded)
    reject("payload-len-too-large", direct, blob[:HEADER_LEN] + b"".join(chunks), "payload_len exceeds bucket - 4; reject after decryption")

    doc = {
        "version": VERSION,
        "constants": {
            "chunk_size": CHUNK_SIZE,
            "header_len": HEADER_LEN,
            "hkdf_info": {"lookup": INFO_LOOKUP.decode(), "kek_direct": INFO_KEK_DIRECT.decode(), "kek_pass": INFO_KEK_PASS.decode()},
            "argon2_defaults": {"m": DEFAULT_ARGON[0], "t": DEFAULT_ARGON[1], "p": DEFAULT_ARGON[2]},
            "argon2_bounds": ARGON_BOUNDS,
        },
        "notes": [
            "Hex fields are raw bytes. *_base64 fields are standard base64; fragments are base64url without padding.",
            "Encryption tests must use the manifest string exactly as given, not re-serialise it.",
            "Argon2 memory (m) is in KiB. pass_key is the 32-byte Argon2id output.",
            "Decryption tests must recover text and files exactly; reject cases must fail for the stated reason.",
        ],
        "vectors": [strip_private(v) for v in vectors],
        "reject": rejects,
    }
    OUT.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT} with {len(vectors)} vectors and {len(rejects)} reject cases")
    for v in vectors:
        e = v["expected"]
        print(f"  {v['name']:32} bucket={e['bucket']:7} chunks={e['chunk_count']} blob_len={e['blob_len']}")


if __name__ == "__main__":
    main()
